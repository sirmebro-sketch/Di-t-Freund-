"""Rebuild the German offline selection from the pinned official USDA archive.

Usage: python3 scripts/import-usda.py /path/to/official.zip
No network, API key, inference of missing nutrients, or personal data.
"""
import hashlib
import json
import math
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SHA256 = '0fe8ae486a2c8eb42cb96413f058deb51863a46c8fb8eeb4b1fb45006dd338ef'
URL = 'https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2018-04.zip'
MICROS = {
    'vitaminC': (1162, 'mg'), 'vitaminD': (1114, 'µg'),
    'vitaminE': (1109, 'mg'), 'vitaminB12': (1178, 'µg'),
    'folate': (1190, 'µg'), 'calcium': (1087, 'mg'),
    'magnesium': (1090, 'mg'), 'potassium': (1092, 'mg'),
    'iodine': (1100, 'µg'), 'selenium': (1103, 'µg'),
    'iron': (1089, 'mg'), 'zinc': (1095, 'mg'),
}

def convert(source, name, stable_id=None):
    ns = {n['nutrient']['id']: n for n in source['foodNutrients']}
    def value(nid, unit, required=False):
        n = ns.get(nid)
        if n is None or n.get('amount') is None:
            if required:
                raise ValueError(f'Missing required nutrient {nid} in {source["fdcId"]}')
            return None
        assert n['nutrient']['unitName'] == unit, (source['fdcId'], nid, unit)
        amount = n['amount']
        assert math.isfinite(amount) and amount >= 0
        return amount
    total = value(1005, 'g', True)
    fiber = value(1079, 'g', True)
    assert fiber <= total + .1
    return {
        'id': stable_id or f'usda-{source["fdcId"]}',
        'name': name, 'fdcId': source['fdcId'],
        'source': f'USDA FoodData Central · SR Legacy · FDC {source["fdcId"]}',
        'kcal': value(1008, 'kcal', True),
        'protein': value(1003, 'g', True),
        'fat': value(1004, 'g', True),
        # US carbohydrate-by-difference includes fibre. Keep source amount
        # for audit; approximation excluding fibre is labelled in the UI.
        'carbs': round(max(0, total-fiber), 3),
        'fiber': fiber, 'usdaTotalCarbs': total,
        'micros': {k: value(*spec) for k, spec in MICROS.items()},
    }

def main():
    data = Path(sys.argv[1]).read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256, 'Unexpected USDA archive'
    with zipfile.ZipFile(Path(sys.argv[1])) as z:
        source = json.loads(z.read('FoodData_Central_sr_legacy_food_json_2018-04.json'))['SRLegacyFoods']
    by_id = {f['fdcId']: f for f in source}
    selection = json.loads((ROOT/'scripts/usda-selection.json').read_text())
    foods = [convert(by_id[row[0]], *row[1:]) for row in selection]
    assert len({f['id'] for f in foods}) == len(foods)
    assert len({f['fdcId'] for f in foods}) == len(foods)
    output = '// Generated by scripts/import-usda.py; USDA CC0, SR Legacy April 2018.\nexport const usdaFoods = ' + json.dumps(foods, ensure_ascii=False, separators=(',', ':')) + ';\n'
    (ROOT/'app/src/main/assets/www/usda-foods.js').write_text(output)
    manifest = {
        'provider': 'USDA FoodData Central', 'dataset': 'SR Legacy April 2018',
        'license': 'CC0 1.0', 'archive': URL, 'archiveSha256': SHA256,
        'generatedSha256': hashlib.sha256(output.encode()).hexdigest(),
        'basis': 'Per 100 g edible portion. Not per 100 ml.',
        'carbohydrates': '1005 minus 1079; approximation excluding fibre, not an EU laboratory measurement.',
        'folate': '1190 DFE, not folic acid or total folate.',
        'vitaminE': '1109 alpha-tocopherol, not total tocopherols.',
        'missing': 'null, never inferred zero. Recorded zero is retained.',
        'records': [{'fdcId': r[0], 'germanName': r[1], 'originalDescription': by_id[r[0]]['description']} for r in selection],
    }
    (ROOT/'docs/USDA-DATA.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
    print(f'Generated {len(foods)} foods; {len(output.encode())} bytes.')

if __name__ == '__main__':
    main()
